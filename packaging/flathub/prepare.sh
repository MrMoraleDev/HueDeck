#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Write the files of the Flathub repository for one Lightloom release (packaging/flathub/README.md):
#
#   io.github.MrMoraleDev.Lightloom.yml  packaging/flatpak's manifest with its working-tree
#                                        source replaced by a git source pinned to the tag
#                                        and its commit
#   cargo-sources.json, node-sources.json  the offline crate and npm sources, generated from
#                                        the Cargo.lock and ui/package-lock.json of that commit
#   flathub.json                         Flathub build options (x86_64 only)
#
# Flathub builds offline from source: the generated lists must match the lock files of the
# pinned commit, so they are generated from that commit, never from the working tree.
#
# Usage: packaging/flathub/prepare.sh --tag vX.Y.Z [--commit SHA] [--out DIR]
#        packaging/flathub/prepare.sh --commit SHA [--out DIR]
#   --tag       release tag; its commit comes from the local repository, else from the remote
#   --commit    full commit SHA (checked against --tag when both are given); without --tag
#               the source is pinned to the commit alone (CI lints the manifest this way)
#   --out       output directory (default: dist/flathub), emptied first
#   --sources-from DIR  copy cargo-sources.json and node-sources.json from DIR instead of
#               generating them (CI: the lists flatpak.yml already generated for the same commit)
#
# Needs git, awk and, unless --sources-from is given, what packaging/flatpak/generate-sources.sh
# needs (python3 with venv, network).

set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
app_id="io.github.MrMoraleDev.Lightloom"
url="https://github.com/MrMoraleDev/Lightloom.git"
manifest="$repo/packaging/flatpak/$app_id.yml"
tag="" commit="" out="$repo/dist/flathub" sources_from=""
while [ $# -gt 0 ]; do
  case "$1" in
    --tag) tag="$2"; shift 2 ;;
    --commit) commit="$2"; shift 2 ;;
    --out) out="$2"; shift 2 ;;
    --sources-from) sources_from="$2"; shift 2 ;;
    -h | --help) sed -n '3,26p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
[ -n "$tag" ] || [ -n "$commit" ] || {
  echo "usage: $0 --tag vX.Y.Z [--commit SHA] [--out DIR] [--sources-from DIR]" >&2
  exit 2
}

# The tag's commit: the local tag if there is one, else the remote's (peeled) tag.
if [ -n "$tag" ]; then
  tagged="$(git -C "$repo" rev-parse -q --verify "refs/tags/$tag^{commit}" 2>/dev/null || true)"
  if [ -z "$tagged" ]; then
    # An annotated tag lists its tag object and, as `<tag>^{}`, the commit it points to.
    tagged="$(git ls-remote "$url" "refs/tags/$tag" "refs/tags/$tag^{}" |
      awk '$2 ~ /\^\{\}$/ { peeled = $1 } $2 !~ /\^\{\}$/ { plain = $1 }
        END { print (peeled != "" ? peeled : plain) }')"
  fi
  [ -n "$tagged" ] || { echo "tag $tag not found locally or on $url" >&2; exit 1; }
  if [ -n "$commit" ] && [ "$commit" != "$tagged" ]; then
    echo "--commit $commit is not the commit of $tag ($tagged)" >&2
    exit 1
  fi
  commit="$tagged"
fi
echo "$commit" | grep -Eq '^[0-9a-f]{40}$' || { echo "not a full commit SHA: $commit" >&2; exit 1; }

rm -rf "$out"
mkdir -p "$out"

# The manifest: a short header instead of the local-build comments, and the git source in
# place of the block between the `flathub-source` markers (same indentation).
if ! grep -q '# flathub-source: begin' "$manifest" || ! grep -q '# flathub-source: end' "$manifest"; then
  echo "$manifest has no flathub-source markers" >&2
  exit 1
fi
{
  echo "# Generated by packaging/flathub/prepare.sh from packaging/flatpak/$app_id.yml"
  echo "# in https://github.com/MrMoraleDev/Lightloom (${tag:-$commit}). Edit it there, not here."
  echo "# Caveats (no CEF effect renderer yet): packaging/flatpak/README.md."
  echo
  awk -v url="$url" -v tag="$tag" -v commit="$commit" '
    !started && /^id:/ { started = 1 }
    !started { next }
    /# flathub-source: begin/ {
      match($0, /^ */); pad = substr($0, 1, RLENGTH)
      print pad "- type: git"
      print pad "  url: " url
      if (tag != "") print pad "  tag: " tag
      print pad "  commit: " commit
      skip = 1; next
    }
    /# flathub-source: end/ { skip = 0; next }
    !skip { print }
  ' "$manifest"
} > "$out/$app_id.yml"
grep -q "commit: $commit" "$out/$app_id.yml"
if grep -q 'type: dir' "$out/$app_id.yml"; then
  echo "the Flathub manifest still has a dir source" >&2
  exit 1
fi

cp "$repo/packaging/flathub/flathub.json" "$out/flathub.json"

if [ -n "$sources_from" ]; then
  cp "$sources_from/cargo-sources.json" "$sources_from/node-sources.json" "$out/"
else
  # The lock files of the pinned commit (a shallow fetch when the commit is not local).
  locks="$(mktemp -d)"
  trap 'rm -rf "$locks"' EXIT
  if ! git -C "$repo" cat-file -e "$commit^{commit}" 2>/dev/null; then
    git -C "$repo" fetch --quiet --depth 1 "$url" "$commit"
  fi
  mkdir -p "$locks/ui"
  git -C "$repo" show "$commit:Cargo.lock" > "$locks/Cargo.lock"
  git -C "$repo" show "$commit:ui/package-lock.json" > "$locks/ui/package-lock.json"
  "$repo/packaging/flatpak/generate-sources.sh" --cargo-lock "$locks/Cargo.lock" \
    --npm-lock "$locks/ui/package-lock.json" --out "$out"
fi

echo "wrote $out:"
ls -l "$out"
