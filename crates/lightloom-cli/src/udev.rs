//! `lightloom udev generate`: the Linux udev rules (`70-lightloom.rules`) that let
//! the unprivileged daemon open the devices the plugins claim
//! (tools/gen-udev/README.md).
//!
//! Input: every `manifest.json` of the plugin directories (a directory holding
//! one, or a directory of plugin directories). Output, deterministic (plugins
//! by id, ids ascending, lower-case hex as sysfs prints them):
//!
//! * per claimed VID:PID, by transport (docs/research/m7-linux-backend.md §1.6):
//!   `hid` → the `hidraw` node; `rawusb` → the `usb_device` node; `hybrid` →
//!   both; `serial` → the `tty` node (and ModemManager told to keep off).
//!   Every rule is restricted to its subsystem so the tag never reaches the
//!   device's `input` or other nodes, has `ACTION!="remove"` (systemd 258
//!   re-applies ACLs on `change`) and adds `TAG+="uaccess"` (an ACL for the
//!   user of the active seat);
//! * SMBus claims add nothing per device; one `i2c-dev` rule puts every
//!   `/dev/i2c-*` in group `i2c` (packaging/sysusers.d/lightloom.conf creates it);
//! * usage claims (any device with a HID LampArray collection) and network
//!   claims have no VID:PID and get a comment only.

use anyhow::Context;
use serde_json::Value;
use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

/// One plugin manifest, reduced to what the rules need.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Claims {
    /// `id`.
    pub id: String,
    /// `name`.
    pub name: String,
    /// `(transport, vid, pid)`, transport lower-case.
    pub usb: Vec<(String, u16, u16)>,
    /// Whether any SMBus claim exists.
    pub smbus: bool,
    /// `(usage_page, usage)` claims.
    pub usages: Vec<(u16, u16)>,
}

/// A manifest usb id: an integer or a hex string (`"0x1462"` or `"1462"`).
fn usb_id(v: &Value) -> Option<u16> {
    match v {
        Value::Number(n) => n.as_u64().and_then(|n| u16::try_from(n).ok()),
        Value::String(s) => {
            let t = s.trim();
            let t = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")).unwrap_or(t);
            u16::from_str_radix(t, 16).ok()
        }
        _ => None,
    }
}

/// Parse one `manifest.json`.
pub fn parse_manifest(text: &str) -> anyhow::Result<Claims> {
    let m: Value = serde_json::from_str(text)?;
    let id = m["id"].as_str().context("manifest has no id")?.to_string();
    let name = m["name"].as_str().unwrap_or(&id).to_string();
    let mut claims = Claims {
        id,
        name,
        usb: Vec::new(),
        smbus: false,
        usages: Vec::new(),
    };
    for d in m["devices"].as_array().into_iter().flatten() {
        if d.get("smbus").is_some() {
            claims.smbus = true;
        } else if let Some(u) = d.get("hidUsage") {
            if let (Some(page), Some(usage)) = (usb_id(&u["usagePage"]), usb_id(&u["usage"])) {
                claims.usages.push((page, usage));
            }
        } else if let Some(vid) = d.get("vid").and_then(usb_id) {
            let transport = d["transport"].as_str().unwrap_or("hid").to_ascii_lowercase();
            for pid in d["pids"].as_array().into_iter().flatten() {
                let pid = usb_id(pid).with_context(|| format!("{}: bad product id {pid}", claims.id))?;
                claims.usb.push((transport.clone(), vid, pid));
            }
        }
    }
    Ok(claims)
}

/// Every manifest under `dirs`, sorted by plugin id.
pub fn load(dirs: &[PathBuf]) -> anyhow::Result<Vec<Claims>> {
    let mut files: Vec<PathBuf> = Vec::new();
    for dir in dirs {
        let own = dir.join("manifest.json");
        if own.is_file() {
            files.push(own);
            continue;
        }
        let entries = std::fs::read_dir(dir).with_context(|| format!("reading {}", dir.display()))?;
        for e in entries {
            let m = e?.path().join("manifest.json");
            if m.is_file() {
                files.push(m);
            }
        }
    }
    let mut out = Vec::new();
    for f in files {
        let text = std::fs::read_to_string(&f).with_context(|| format!("reading {}", f.display()))?;
        out.push(parse_manifest(&text).with_context(|| format!("parsing {}", f.display()))?);
    }
    out.sort_by(|a, b| a.id.cmp(&b.id));
    Ok(out)
}

const HEADER: &str = "\
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Lightloom udev rules. Generated by `lightloom udev generate` from the plugin manifests;
# do not edit (regenerate instead).
#
# Install (once, as root), then replug the devices or trigger:
#   install -m 0644 70-lightloom.rules /etc/udev/rules.d/70-lightloom.rules
#   udevadm control --reload-rules && udevadm trigger
# Packages install it as /usr/lib/udev/rules.d/70-lightloom.rules. The number must stay
# below 73 (73-seat-late.rules applies the uaccess tag).
#
# TAG+=\"uaccess\" gives the user of the active local seat an ACL on the node: only the
# hidraw / usb_device / tty node of a claimed VID:PID, never its input nodes.
";

const I2C_RULE: &str = "\
# SMBus / I2C adapters (RAM, motherboard and GPU lighting through /dev/i2c-*): group i2c.
# Create the group and join it once: packaging/sysusers.d/lightloom.conf (or
# `groupadd -r i2c`), then `usermod -aG i2c $USER` and log in again.
ACTION!=\"remove\", SUBSYSTEM==\"i2c-dev\", KERNEL==\"i2c-[0-9]*\", GROUP=\"i2c\", MODE=\"0660\"
";

fn rule_lines(transport: &str, vid: u16, pid: u16) -> Vec<String> {
    let ids = format!("ATTRS{{idVendor}}==\"{vid:04x}\", ATTRS{{idProduct}}==\"{pid:04x}\"");
    let hidraw = format!("ACTION!=\"remove\", SUBSYSTEM==\"hidraw\", {ids}, TAG+=\"uaccess\"");
    let usb = format!(
        "ACTION!=\"remove\", SUBSYSTEM==\"usb\", ENV{{DEVTYPE}}==\"usb_device\", \
         ATTR{{idVendor}}==\"{vid:04x}\", ATTR{{idProduct}}==\"{pid:04x}\", TAG+=\"uaccess\""
    );
    let tty = format!(
        "ACTION!=\"remove\", SUBSYSTEM==\"tty\", {ids}, TAG+=\"uaccess\", ENV{{ID_MM_DEVICE_IGNORE}}=\"1\""
    );
    match transport {
        "rawusb" => vec![usb],
        "hybrid" => vec![hidraw, usb],
        "serial" => vec![tty],
        _ => vec![hidraw],
    }
}

/// The rules file for `plugins`.
pub fn render(plugins: &[Claims]) -> String {
    let mut out = String::from(HEADER);
    let mut emitted: BTreeSet<String> = BTreeSet::new();
    for p in plugins {
        let mut ids: Vec<(String, u16, u16)> = p.usb.clone();
        ids.sort_by(|a, b| (a.1, a.2, &a.0).cmp(&(b.1, b.2, &b.0)));
        ids.dedup();
        let mut lines = Vec::new();
        for (transport, vid, pid) in &ids {
            for line in rule_lines(transport, *vid, *pid) {
                if emitted.insert(line.clone()) {
                    lines.push(line);
                }
            }
        }
        let notes: Vec<String> = p
            .usages
            .iter()
            .map(|(page, usage)| {
                format!(
                    "# (usage 0x{page:04x}/0x{usage:04x} claim: no VID:PID; such devices need their own rule)"
                )
            })
            .collect();
        if lines.is_empty() && notes.is_empty() {
            continue;
        }
        out.push('\n');
        out.push_str(&format!("# {}: {}\n", p.id, p.name));
        for l in notes.iter().chain(&lines) {
            out.push_str(l);
            out.push('\n');
        }
    }
    out.push('\n');
    out.push_str(I2C_RULE);
    out
}

/// `lightloom udev generate`: print, write `out`, or with `check` compare
/// `out` with what would be written. Returns whether everything is clean.
pub fn generate(dirs: &[PathBuf], out: Option<&Path>, check: bool) -> anyhow::Result<bool> {
    let rules = render(&load(dirs)?);
    match (out, check) {
        (Some(path), true) => {
            let current = std::fs::read_to_string(path)
                .unwrap_or_default()
                .replace("\r\n", "\n");
            if current == rules {
                Ok(true)
            } else {
                eprintln!(
                    "lightloom udev: {} is out of date; run `lightloom udev generate --out {}`",
                    path.display(),
                    path.display()
                );
                Ok(false)
            }
        }
        (None, true) => anyhow::bail!("--check needs --out <file>"),
        (Some(path), false) => {
            std::fs::write(path, &rules).with_context(|| format!("writing {}", path.display()))?;
            Ok(true)
        }
        (None, false) => {
            print!("{rules}");
            Ok(true)
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    #[test]
    fn manifest_ids_in_every_form() {
        let c = parse_manifest(
            r#"{"id":"x.y","name":"Y","devices":[
                {"vid":"0x1462","pids":["0x7C91", "7c92", 31891],"transport":"hid"},
                {"vid":4660,"pids":["0x0001"],"transport":"hybrid"},
                {"vid":"0x0403","pids":["0x6001"],"transport":"serial"},
                {"hidUsage":{"usagePage":"0x59","usage":"0x01"},"transport":"hid"},
                {"smbus":{"addresses":[80]}}]}"#,
        )
        .unwrap();
        assert_eq!(
            c.usb,
            vec![
                ("hid".into(), 0x1462, 0x7c91),
                ("hid".into(), 0x1462, 0x7c92),
                ("hid".into(), 0x1462, 0x7c93),
                ("hybrid".into(), 0x1234, 0x0001),
                ("serial".into(), 0x0403, 0x6001),
            ]
        );
        assert!(c.smbus);
        assert_eq!(c.usages, vec![(0x59, 0x01)]);
        assert!(parse_manifest(r#"{"name":"no id"}"#).is_err());
        assert!(parse_manifest(r#"{"id":"a","devices":[{"vid":"0x1","pids":["zz"]}]}"#).is_err());
    }

    #[test]
    fn rules_are_scoped_sorted_and_lower_case() {
        let c = parse_manifest(
            r#"{"id":"b.b","name":"B","devices":[
                {"vid":"0x1E71","pids":["0x2007","0x2001"]},
                {"vid":"0x1234","pids":["0xABCD"],"transport":"rawusb"},
                {"vid":"0x0403","pids":["0x6001"],"transport":"serial"}]}"#,
        )
        .unwrap();
        let dup = parse_manifest(r#"{"id":"c.c","name":"C","devices":[{"vid":"0x1e71","pids":["0x2001"]}]}"#)
            .unwrap();
        let r = render(&[c, dup]);
        let rules: Vec<&str> = r.lines().filter(|l| l.starts_with("ACTION")).collect();
        assert_eq!(
            rules,
            vec![
                r#"ACTION!="remove", SUBSYSTEM=="tty", ATTRS{idVendor}=="0403", ATTRS{idProduct}=="6001", TAG+="uaccess", ENV{ID_MM_DEVICE_IGNORE}="1""#,
                r#"ACTION!="remove", SUBSYSTEM=="usb", ENV{DEVTYPE}=="usb_device", ATTR{idVendor}=="1234", ATTR{idProduct}=="abcd", TAG+="uaccess""#,
                r#"ACTION!="remove", SUBSYSTEM=="hidraw", ATTRS{idVendor}=="1e71", ATTRS{idProduct}=="2001", TAG+="uaccess""#,
                r#"ACTION!="remove", SUBSYSTEM=="hidraw", ATTRS{idVendor}=="1e71", ATTRS{idProduct}=="2007", TAG+="uaccess""#,
                r#"ACTION!="remove", SUBSYSTEM=="i2c-dev", KERNEL=="i2c-[0-9]*", GROUP="i2c", MODE="0660""#,
            ]
        );
        assert!(r.contains("# b.b: B\n"));
        assert!(
            !r.contains("# c.c"),
            "a plugin whose ids are all emitted already adds nothing"
        );
    }

    #[test]
    fn first_party_rules_match_the_packaged_file() {
        let plugins = load(&[repo().join("plugins")]).unwrap();
        assert!(plugins.len() >= 10);
        let rules = render(&plugins);
        // No uppercase hex in ids, every VID:PID line unique, nothing unscoped.
        let lines: Vec<&str> = rules.lines().filter(|l| l.starts_with("ACTION")).collect();
        let unique: BTreeSet<&&str> = lines.iter().collect();
        assert_eq!(unique.len(), lines.len());
        for l in &lines {
            assert!(l.contains("SUBSYSTEM=="), "{l}");
            assert!(!l.contains("SUBSYSTEMS=="), "{l}");
        }
        assert!(rules.contains(r#"ATTRS{idVendor}=="1462", ATTRS{idProduct}=="7c91""#));
        assert!(rules.contains("# lightloom.hid-lamparray: HID LampArray\n"));
        let packaged = std::fs::read_to_string(repo().join("packaging/udev/70-lightloom.rules"))
            .unwrap()
            .replace("\r\n", "\n");
        assert!(
            packaged == rules,
            "packaging/udev/70-lightloom.rules is stale: run `lightloom udev generate --plugins plugins --out packaging/udev/70-lightloom.rules`"
        );
    }

    #[test]
    fn check_mode_compares_with_the_file() {
        let dir = std::env::temp_dir().join(format!("lightloom-udev-{}", std::process::id()));
        let plugin = dir.join("p");
        std::fs::create_dir_all(&plugin).unwrap();
        std::fs::write(
            plugin.join("manifest.json"),
            r#"{"id":"t.p","name":"P","devices":[{"vid":"0x1","pids":["0x2"]}]}"#,
        )
        .unwrap();
        let out = dir.join("70-lightloom.rules");
        assert!(!generate(std::slice::from_ref(&dir), Some(&out), true).unwrap());
        assert!(generate(std::slice::from_ref(&dir), Some(&out), false).unwrap());
        assert!(generate(std::slice::from_ref(&plugin), Some(&out), true).unwrap());
        assert!(generate(std::slice::from_ref(&dir), None, true).is_err());
        let _ = std::fs::remove_dir_all(&dir);
    }
}
